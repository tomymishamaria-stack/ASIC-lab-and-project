module tb_fsm_full;

reg clk, rst, x;
wire y;

fsm_cov dut (
    .clk(clk),
    .rst(rst),
    .x(x),
    .y(y)
);

// Clock generation
always #5 clk = ~clk;

initial begin
    clk = 0;
    rst = 1;
    x = 0;

    // Reset
    #10;
    rst = 0;

    //--------------------------------------------------
    // Cover S0 -> S0
    //--------------------------------------------------
    x = 0;
    #10;

    //--------------------------------------------------
    // Cover S0 -> S1
    //--------------------------------------------------
    x = 1;
    #10;

    //--------------------------------------------------
    // Cover S1 -> S0
    //--------------------------------------------------
    x = 0;
    #10;

    //--------------------------------------------------
    // Cover S0 -> S1 again
    //--------------------------------------------------
    x = 1;
    #10;

    //--------------------------------------------------
    // Cover S1 -> S2
    //--------------------------------------------------
    x = 1;
    #10;

    //--------------------------------------------------
    // Cover S2 -> S0 with x = 1
    //--------------------------------------------------
    x = 1;
    #10;

    //--------------------------------------------------
    // Reach S2 again
    //--------------------------------------------------
    x = 1;
    #10;      // S0 -> S1

    x = 1;
    #10;      // S1 -> S2

    //--------------------------------------------------
    // Cover S2 -> S0 with x = 0
    //--------------------------------------------------
    x = 0;
    #10;

    $finish;
end

endmodule
